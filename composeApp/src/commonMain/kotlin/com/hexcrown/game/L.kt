package com.hexcrown.game

import androidx.compose.runtime.mutableIntStateOf

/** Every player-facing text, French then English. The stored choice wins over the system language (0 = follow the system). */
object L {
    private val current by lazy {
        val saved = Storage.loadInt("lang")
        mutableIntStateOf(if (saved > 0) saved - 1 else if (systemLanguage() == "fr") 0 else 1)
    }
    /** 0 French, 1 English. Backed by Compose state: screens re-read their text when it changes. */
    val lang: Int get() = current.intValue

    fun setLang(l: Int) { Storage.saveInt("lang", l + 1); current.intValue = l }

    operator fun get(key: String): String = TEXTS[key]?.get(lang) ?: key

    /** Text with {0}, {1}… filled in. */
    fun f(key: String, vararg args: Any): String {
        var s = get(key)
        for (i in args.indices) s = s.replace("{$i}", args[i].toString())
        return s
    }
}

/** A translated name table, indexed like the plain array it replaces. */
class LArr(private vararg val keys: String) {
    operator fun get(i: Int) = L[keys[i]]
    val size get() = keys.size
    val indices get() = keys.indices
}

