const val PROP_TENT = 0f
const val PROP_BARREL = 1f
const val PROP_CRATE = 2f
const val PROP_WHEELBARROW = 3f
const val PROP_LUMBER = 4f
const val PROP_WEAPONRACK = 5f
const val PROP_STUMP = 6f
const val PROP_BUSH = 7f

/** Mutable 2D vector reused to avoid allocations in the game loop. */
class Vec {
    var x = 0f
    var y = 0f
}

/** Polyline path that enemies follow, sampled by distance travelled. */
class GamePath(pts: FloatArray) {
    val n = pts.size / 2
    val xs = FloatArray(n) { pts[it * 2] }
    val ys = FloatArray(n) { pts[it * 2 + 1] }
    private val cum = FloatArray(n)
    val length: Float

    init {
        for (i in 1 until n) cum[i] = cum[i - 1] + hypot(xs[i] - xs[i - 1], ys[i] - ys[i - 1])
        length = cum[n - 1]
    }

    fun sample(s: Float, out: Vec) {
        val ss = s.coerceIn(0f, length)
        var i = 1
        while (i < n - 1 && cum[i] < ss) i++
        val seg = cum[i] - cum[i - 1]
        val t = if (seg > 0f) (ss - cum[i - 1]) / seg else 0f
        out.x = xs[i - 1] + (xs[i] - xs[i - 1]) * t
        out.y = ys[i - 1] + (ys[i] - ys[i - 1]) * t
    }

    /** Unit tangent at distance s. */
    fun tangent(s: Float, out: Vec) {
        val ss = s.coerceIn(0f, length)
        var i = 1
        while (i < n - 1 && cum[i] < ss) i++
        val dx = xs[i] - xs[i - 1]
        val dy = ys[i] - ys[i - 1]
        val l = hypot(dx, dy).coerceAtLeast(0.001f)
        out.x = dx / l
        out.y = dy / l
    }
}

/** Map layout: roads, cliffs, decoration and building spots. Level 1 is hand-made, later levels are generated by [load]. */
object World {
    const val W = 2000f
    const val H = 2400f

    const val CASTLE_X = 1000f
    const val CASTLE_Y = 1650f
    const val CASTLE_R = 95f

    const val HOUSE_X = 690f
    const val HOUSE_Y = 1440f

    // base buildings (pads), chosen clear of every road of every level and of the enclosure
    const val FARM_X = 470f
    const val FARM_Y = 1560f
    const val BARRACKS_X = 800f
    const val BARRACKS_Y = 1900f
    const val MINE_X = 1300f
    const val MINE_Y = 1800f

    const val KING_START_X = 820f
    const val KING_START_Y = 1720f

    /** Bumped by [load]; the renderer rebuilds its cached road paths when it changes. */
    var version = 0
        private set

    /** Enemy roads. Level 1: 0 = north-east, 1 = east, 2 = south. */
    private val paths1 = arrayOf(
        GamePath(floatArrayOf(1720f, -80f, 1580f, 380f, 1270f, 690f, 1160f, 1120f, 1030f, 1545f)),
        GamePath(floatArrayOf(2100f, 1280f, 1720f, 1340f, 1420f, 1560f, 1095f, 1650f)),
        GamePath(floatArrayOf(640f, 2500f, 780f, 2120f, 960f, 1900f, 1000f, 1750f)),
    )

    /** Purely decorative roads (x0,y0,x1,y1...). */
    private val decoRoads1 = arrayOf(
        floatArrayOf(-50f, 1980f, 420f, 1860f, 760f, 1750f, 900f, 1690f),
        floatArrayOf(690f, 1500f, 760f, 1640f, 900f, 1680f),
        floatArrayOf(1160f, 1120f, 1500f, 1180f, 2060f, 1050f),
    )

    /** Cliff blocks: x, y, w, d (ground footprint), height. */
    private val cliffs1 = arrayOf(
        floatArrayOf(-40f, -40f, 760f, 520f, 210f),
        floatArrayOf(-40f, 440f, 430f, 420f, 230f),
        floatArrayOf(600f, -40f, 420f, 300f, 170f),
        floatArrayOf(330f, 470f, 300f, 230f, 150f),
        floatArrayOf(-40f, 820f, 250f, 520f, 200f),
        floatArrayOf(1850f, 1700f, 260f, 400f, 160f),
    )

    /** Towers spots (x,y) next to each road. */
    private val towerSpots1 = floatArrayOf(1330f, 1010f, 1560f, 1600f, 1120f, 2040f)

    /** Palisade location along each road, as a fraction of its length. */
    private val wallFractions1 = floatArrayOf(0.66f, 0.42f, 0.42f)

    var paths = paths1; private set
    var decoRoads = decoRoads1; private set
    var cliffs = cliffs1; private set
    var towerSpots = towerSpots1; private set
    var wallFractions = wallFractions1; private set
    var trees = FloatArray(0); private set
    var rocks = FloatArray(0); private set
    var grassPatches = FloatArray(0); private set
    /** Ground details: grass tufts (x, y, size), flowers (x, y, colour 0..2), pebbles along road edges (x, y, radius). */
    var tufts = FloatArray(0); private set
    var flowers = FloatArray(0); private set
    var pebbles = FloatArray(0); private set
    /** Props in the depth sort (x, y, kind): see PROP_* ; camp clutter near the base plus bushes and stumps. */
    var props = FloatArray(0); private set

    /**
     * Hand-made levels. Each level keeps everything before it and adds one road with its own landmark:
     * 2 = northern forest (road through a cliff pass and a dense wood), 3 = eastern gorge (road squeezed between
     * two cliffs), 4 = southern river (crossed by both southern roads on bridges). Level 5+ keeps the level-4 map.
     */
    val LEVEL_NAMES = arrayOf(
        // chapter 1, the plain: the map grows road by road
        "La Vallée", "La Forêt du Nord", "Le Col de l'Est", "La Rivière du Sud", "Le Seigneur de la Plaine",
        // chapter 2, the forest
        "L'Orée", "Les Loups des Bois", "La Clairière", "Les Archers Verts", "Le Cœur de la Forêt",
        // chapter 3, the snow
        "Le Premier Gel", "La Tempête", "Les Remparts Gelés", "La Nuit Blanche", "L'Ogre des Neiges",
        // chapter 4, the kingdom
        "Les Bannières", "Le Siège", "Les Béliers", "La Dernière Muraille", "Le Seigneur Noir",
    )
    val CHAPTER_NAMES = arrayOf("La Plaine", "La Forêt", "Les Neiges", "Le Royaume")
    const val LAST_LEVEL = 20
    fun levelName(level: Int) = if (level > LAST_LEVEL) "Mode infini" else LEVEL_NAMES[(level - 1).coerceIn(0, LEVEL_NAMES.size - 1)]
    /** 0 plain (1-5), 1 forest (6-10), 2 snow (11-15), 3 kingdom (16-20 and the endless mode). */
    fun chapter(level: Int) = ((level - 1) / 5).coerceIn(0, 3)
    /** Extra woods for the forest chapter. */
    private val chapterForests = floatArrayOf(
        250f, 620f, 160f, 14f, 1500f, 700f, 150f, 12f, 1750f, 1450f, 130f, 10f, 300f, 1400f, 140f, 12f,
        1650f, 2050f, 120f, 9f, 500f, 2150f, 120f, 9f, 1200f, 420f, 120f, 9f,
    )

    private val extraRoads = arrayOf(
        floatArrayOf(380f, -80f, 470f, 320f, 610f, 720f, 770f, 1060f, 915f, 1380f, 985f, 1560f),
        floatArrayOf(2100f, 520f, 1800f, 660f, 1560f, 900f, 1360f, 1150f, 1160f, 1440f, 1060f, 1580f),
        floatArrayOf(1290f, 2500f, 1200f, 2120f, 1060f, 1900f, 1030f, 1752f),
    )
    private val extraTowers = arrayOf(floatArrayOf(470f, 960f), floatArrayOf(1580f, 1160f), floatArrayOf(1420f, 1990f))
    private val extraWallFractions = floatArrayOf(0.62f, 0.55f, 0.4f)
    /** Cliffs added by each new level (x, y, w, d, height), shaping its landmark. */
    private val extraCliffs = arrayOf(
        arrayOf(floatArrayOf(-40f, -40f, 330f, 560f, 210f), floatArrayOf(580f, -40f, 300f, 360f, 180f)),
        arrayOf(floatArrayOf(1640f, 360f, 440f, 210f, 170f), floatArrayOf(1720f, 820f, 380f, 250f, 160f)),
        arrayOf(),
    )
    /** Forest clusters added by each level (x, y, radius, trees). */
    private val extraForests = arrayOf(
        floatArrayOf(420f, 760f, 150f, 12f, 820f, 780f, 130f, 9f, 300f, 1120f, 150f, 10f, 700f, 420f, 110f, 7f),
        floatArrayOf(1500f, 520f, 120f, 7f, 1900f, 1180f, 110f, 6f),
        floatArrayOf(400f, 2050f, 140f, 9f, 1700f, 2150f, 140f, 9f),
    )
    /** Southern river (level 4+): polyline and half width; the roads cross it on bridges. */
    private val riverPts = floatArrayOf(-80f, 2300f, 300f, 2240f, 700f, 2275f, 1000f, 2230f, 1300f, 2270f, 1700f, 2220f, 2080f, 2260f)
    const val RIVER_HALF = 38f
    var river = FloatArray(0); private set
    var forests = FloatArray(0); private set

    init {
        decorate(7)
    }

    /** The map persists and grows: level N keeps every road, tower spot and palisade of level N-1 and adds the next hand-made road. */
    fun load(level: Int) {
        val extra = min(level - 1, extraRoads.size)
        paths = paths1; towerSpots = towerSpots1; wallFractions = wallFractions1; decoRoads = decoRoads1; cliffs = cliffs1
        var fr = FloatArray(0)
        for (k in 0 until extra) {
            val path = GamePath(extraRoads[k])
            paths = paths + path
            towerSpots = towerSpots + extraTowers[k]
            wallFractions = wallFractions + extraWallFractions[k]
            cliffs = cliffs.filter { pathClear(it, path, 70f) }.toTypedArray() + extraCliffs[k]
            fr = fr + extraForests[k]
        }
        if (chapter(level) == 1) fr = fr + chapterForests
        forests = fr
        river = if (level >= 4) riverPts else FloatArray(0)
        decorate(7)
        version++
    }

    /** True in the river, except on the bridges (where a road crosses). */
    fun inRiver(x: Float, y: Float): Boolean {
        val r = river
        var i = 0
        var inside = false
        while (i + 3 < r.size) {
            if (segDist(x, y, r[i], r[i + 1], r[i + 2], r[i + 3]) < RIVER_HALF) { inside = true; break }
            i += 2
        }
        return inside && distToRoads(x, y) > 52f
    }

    /** On the river's water line itself (ignoring bridges): where the renderer puts bridges. */
    fun inRiverCore(x: Float, y: Float) = inRiverBand(x, y, -10f)

    private fun inRiverBand(x: Float, y: Float, margin: Float): Boolean {
        val r = river
        var i = 0
        while (i + 3 < r.size) {
            if (segDist(x, y, r[i], r[i + 1], r[i + 2], r[i + 3]) < RIVER_HALF + margin) return true
            i += 2
        }
        return false
    }

    private fun segDist(x: Float, y: Float, x0: Float, y0: Float, x1: Float, y1: Float): Float {
        val sx = x1 - x0; val sy = y1 - y0
        val l2 = sx * sx + sy * sy
        val t = if (l2 > 0f) (((x - x0) * sx + (y - y0) * sy) / l2).coerceIn(0f, 1f) else 0f
        return hypot(x - (x0 + sx * t), y - (y0 + sy * t))
    }

    private fun pathClear(c: FloatArray, p: GamePath, margin: Float): Boolean {
        val v = Vec()
        var s = 0f
        while (s <= p.length) {
            p.sample(s, v)
            if (v.x > c[0] - margin && v.x < c[0] + c[2] + margin && v.y > c[1] - c[4] - margin && v.y < c[1] + c[3] + margin) return false
            s += 30f
        }
        return true
    }

    private fun nearDecoRoad(x: Float, y: Float, d: Float): Boolean {
        for (road in decoRoads) {
            var i = 0
            while (i + 3 < road.size) {
                // distance to each segment, sampled every 20 units
                val x0 = road[i]; val y0 = road[i + 1]; val x1 = road[i + 2]; val y1 = road[i + 3]
                val n = (hypot(x1 - x0, y1 - y0) / 20f).toInt() + 1
                for (k in 0..n) {
                    val t = k.toFloat() / n
                    if (hypot(x - (x0 + (x1 - x0) * t), y - (y0 + (y1 - y0) * t)) < d) return true
                }
                i += 2
            }
        }
        return false
    }

    private fun distToRoads(x: Float, y: Float): Float {
        val v = Vec()
        var best = Float.MAX_VALUE
        for (p in paths) {
            var s = 0f
            while (s <= p.length) {
                p.sample(s, v)
                best = min(best, hypot(x - v.x, y - v.y))
                s += 20f
            }
        }
        return best
    }

    private fun decorate(seed: Int) {
        val rnd = Random(seed)
        val t = ArrayList<Float>()
        var tries = 0
        var fi = 0
        while (fi + 3 < forests.size) {
            val cx = forests[fi]; val cy = forests[fi + 1]; val cr = forests[fi + 2]
            var placed = 0
            var ft = 0
            while (placed < forests[fi + 3].toInt() && ft++ < 200) {
                val a = rnd.nextFloat() * 2f * PI.toFloat()
                val d = sqrt(rnd.nextFloat()) * cr
                val x = cx + cos(a) * d; val y = cy + sin(a) * d * 0.8f
                if (!isFreeForDecor(x, y, 90f)) continue
                t.add(x); t.add(y); t.add(0.9f + rnd.nextFloat() * 0.6f)
                placed++
            }
            fi += 4
        }
        while (t.size < (46 + forests.size / 4 * 9) * 3 && tries < 4000) {
            tries++
            val x = rnd.nextFloat() * W
            val y = rnd.nextFloat() * H
            if (!isFreeForDecor(x, y, 120f)) continue
            t.add(x); t.add(y); t.add(0.8f + rnd.nextFloat() * 0.6f)
        }
        trees = t.toFloatArray()
        val r = ArrayList<Float>()
        tries = 0
        while (r.size < 24 * 3 && tries < 4000) {
            tries++
            val x = rnd.nextFloat() * W
            val y = rnd.nextFloat() * H
            if (!isFreeForDecor(x, y, 70f)) continue
            r.add(x); r.add(y); r.add(0.6f + rnd.nextFloat() * 0.8f)
        }
        rocks = r.toFloatArray()
        val g = ArrayList<Float>()
        repeat(90) {
            g.add(rnd.nextFloat() * W); g.add(rnd.nextFloat() * H); g.add(60f + rnd.nextFloat() * 140f); g.add(rnd.nextFloat())
        }
        grassPatches = g.toFloatArray()
        val tf = ArrayList<Float>()
        tries = 0
        while (tf.size < 900 * 3 && tries < 6000) {
            tries++
            val x = rnd.nextFloat() * W
            val y = rnd.nextFloat() * H
            if (insideCliff(x, y, 10f) || distToRoads(x, y) < 62f || (river.isNotEmpty() && inRiverBand(x, y, 6f))) continue
            tf.add(x); tf.add(y); tf.add(0.7f + rnd.nextFloat() * 0.7f)
        }
        tufts = tf.toFloatArray()
        val fl = ArrayList<Float>()
        tries = 0
        while (fl.size < 70 * 3 * 5 && tries < 3000) { // clusters of 5
            tries++
            val cx = rnd.nextFloat() * W
            val cy = rnd.nextFloat() * H
            if (insideCliff(cx, cy, 30f) || distToRoads(cx, cy) < 90f || hypot(cx - CASTLE_X, cy - CASTLE_Y) < 220f || nearDecoRoad(cx, cy, 80f) || (river.isNotEmpty() && inRiverBand(cx, cy, 20f))) continue
            val col = rnd.nextInt(3).toFloat()
            repeat(5) { fl.add(cx + (rnd.nextFloat() - 0.5f) * 50f); fl.add(cy + (rnd.nextFloat() - 0.5f) * 30f); fl.add(col) }
        }
        flowers = fl.toFloatArray()
        val pb = ArrayList<Float>()
        val v = Vec(); val tg = Vec()
        for (p in paths) {
            var s = 30f
            while (s < p.length - 120f) {
                p.sample(s, v); p.tangent(s, tg)
                val side = if (rnd.nextBoolean()) 1f else -1f
                val off = 46f + rnd.nextFloat() * 10f
                pb.add(v.x - tg.y * off * side); pb.add(v.y + tg.x * off * side); pb.add(3f + rnd.nextFloat() * 4f)
                s += 35f + rnd.nextFloat() * 50f
            }
        }
        pebbles = pb.toFloatArray()
        val pr = ArrayList<Float>()
        // camp clutter around the archer house and the keep, dropped where a road or pad would cover it
        val camp = floatArrayOf(
            470f, 1430f, PROP_TENT, 540f, 1505f, PROP_BARREL, 563f, 1520f, PROP_BARREL, 515f, 1530f, PROP_CRATE,
            785f, 1370f, PROP_LUMBER, 850f, 1405f, PROP_WHEELBARROW, 800f, 1480f, PROP_WEAPONRACK,
            1200f, 1705f, PROP_CRATE, 1228f, 1690f, PROP_BARREL, 860f, 1850f, PROP_LUMBER, 1250f, 1960f, PROP_TENT,
            880f, 1560f, PROP_BARREL,
        )
        val pads = floatArrayOf(720f, 1600f, 560f, 1640f, 1170f, 1800f, KING_START_X, KING_START_Y, FARM_X, FARM_Y, BARRACKS_X, BARRACKS_Y, MINE_X, MINE_Y)
        var j = 0
        while (j < camp.size) {
            val x = camp[j]; val y = camp[j + 1]
            var ok = distToRoads(x, y) > 75f && hypot(x - CASTLE_X, y - CASTLE_Y) > 150f && !nearDecoRoad(x, y, 60f)
            var q = 0
            while (q < pads.size) { if (hypot(x - pads[q], y - pads[q + 1]) < 85f) ok = false; q += 2 }
            if (ok) { pr.add(x); pr.add(y); pr.add(camp[j + 2]) }
            j += 3
        }
        tries = 0
        var nb = 0
        while (nb < 34 && tries < 2000) {
            tries++
            val x = rnd.nextFloat() * W
            val y = rnd.nextFloat() * H
            if (!isFreeForDecor(x, y, 90f)) continue
            pr.add(x); pr.add(y); pr.add(if (nb % 4 == 3) PROP_STUMP else PROP_BUSH)
            nb++
        }
        props = pr.toFloatArray()
    }

    fun insideCliff(x: Float, y: Float, margin: Float): Boolean {
        for (c in cliffs) {
            if (x > c[0] - margin && x < c[0] + c[2] + margin && y > c[1] - margin && y < c[1] + c[3] + margin) return true
        }
        return false
    }

    private fun isFreeForDecor(x: Float, y: Float, clearance: Float): Boolean {
        if (insideCliff(x, y, 30f)) return false
        if (river.isNotEmpty() && inRiverBand(x, y, 30f)) return false
        // keep the base area clear
        if (hypot(x - CASTLE_X, y - CASTLE_Y) < 520f) return false
        val v = Vec()
        for (p in paths) {
            var s = 0f
            while (s <= p.length) {
                p.sample(s, v)
                if (hypot(x - v.x, y - v.y) < clearance) return false
                s += 40f
            }
        }
        for (road in decoRoads) {
            var i = 0
            while (i < road.size) {
                if (hypot(x - road[i], y - road[i + 1]) < clearance + 40f) return false
                i += 2
            }
        }
        var i = 0
        while (i < towerSpots.size) {
            if (hypot(x - towerSpots[i], y - towerSpots[i + 1]) < 200f) return false
            i += 2
        }
        return true
    }
}
