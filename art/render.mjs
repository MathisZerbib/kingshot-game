// Renders all 3D models into sprite atlases: node render.mjs
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const here = path.dirname(new URL(import.meta.url).pathname);
const outDir = path.resolve(here, '../composeApp/src/commonMain/composeResources/drawable');
const ktFile = path.resolve(here, '../composeApp/src/commonMain/kotlin/fr/kingshot/game/SpriteData.kt');
fs.mkdirSync(outDir, { recursive: true });

const types = { '.html': 'text/html', '.js': 'text/javascript' };
const server = http.createServer((req, res) => {
  const p = path.join(here, decodeURIComponent(req.url.split('?')[0]));
  if (!p.startsWith(here) || !fs.existsSync(p)) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'content-type': types[path.extname(p)] || 'application/octet-stream' });
  fs.createReadStream(p).pipe(res);
});
await new Promise(r => server.listen(0, r));
const port = server.address().port;

const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
page.on('console', m => console.log('[page]', m.text()));
page.on('pageerror', e => console.log('[pageerror]', e.message));
await page.goto(`http://localhost:${port}/render.html`);
await page.waitForFunction('window.ready === true');

const save = (name, url) => fs.writeFileSync(path.join(outDir, name + '.png'), Buffer.from(url.split(',')[1], 'base64'));
const meta = [];

const walk = n => Array.from({ length: n }, (_, i) => ({ mode: 'walk', t: i / n }));
const units = {
  archer: { w: 112, h: 128, ppu: 2, ax: 56, ay: 108, frames: [{ mode: 'walk', t: 0 }, ...walk(6), { mode: 'shoot', t: 0.25 }, { mode: 'shoot', t: 0.7 }, { mode: 'shoot', t: 0.95 }] },
  knight: { w: 128, h: 152, ppu: 2, ax: 64, ay: 128, frames: [...walk(6), { mode: 'attack', t: 0.3 }, { mode: 'attack', t: 0.55 }, { mode: 'attack', t: 0.85 }] },
  boss: { w: 200, h: 236, ppu: 1.3, ax: 100, ay: 200, scale: 2.2, frames: [...walk(4), { mode: 'attack', t: 0.3 }, { mode: 'attack', t: 0.55 }, { mode: 'attack', t: 0.85 }] },
  king: { w: 200, h: 200, ppu: 2, ax: 100, ay: 156, frames: [{ mode: 'idle', t: 0 }, ...walk(6)] },
};
for (const [name, spec] of Object.entries(units)) {
  const t0 = Date.now();
  const url = await page.evaluate(([n, s]) => window.renderUnit(n, s), [name, spec]);
  save(name, url);
  meta.push({ name, w: spec.w, h: spec.h, ax: spec.ax, ay: spec.ay, ppu: spec.ppu, cols: spec.frames.length, rows: 8 });
  console.log(name, Date.now() - t0, 'ms');
}
const statics = {
  castle: { ppu: 1.2, size: 1000 }, house: { ppu: 1.4, size: 900, rotY: 0.35 }, tower: { ppu: 1.5, size: 700, rotY: 0.3 },
  stake: { ppu: 2, size: 300 }, pine0: { ppu: 1.6, size: 500 }, pine1: { ppu: 1.6, size: 500 },
  roundtree: { ppu: 1.6, size: 500 }, rock0: { ppu: 1.6, size: 300 }, rock1: { ppu: 1.6, size: 300 },
};
for (const [name, spec] of Object.entries(statics)) {
  const r = await page.evaluate(([n, s]) => window.renderStatic(n, s), [name, spec]);
  save(name, r.url);
  meta.push({ name, w: r.w, h: r.h, ax: r.ax, ay: r.ay, ppu: spec.ppu, cols: 1, rows: 1 });
  console.log(name, r.w, r.h);
}
const coins = await page.evaluate(() => window.renderCoins());
save('coin_spin', coins.spin.url);
meta.push({ name: 'coin_spin', w: coins.spin.w, h: coins.spin.h, ax: coins.spin.ax, ay: coins.spin.ay, ppu: 1.6, cols: 8, rows: 1 });
save('coin_flat', coins.flat.url);
meta.push({ name: 'coin_flat', w: coins.flat.w, h: coins.flat.h, ax: coins.flat.ax, ay: coins.flat.ay, ppu: 1.6, cols: 1, rows: 1 });

await browser.close();
server.close();

const camel = s => s.replace(/_(\w)/g, (_, c) => c.toUpperCase());
const kt = `package fr.kingshot.game

// Generated by art/render.mjs — do not edit by hand.

/** Layout of a sprite atlas: cells of [w]x[h] px, [cols] frames per row, one row per direction. */
class SpriteInfo(val w: Int, val h: Int, val ax: Float, val ay: Float, val ppu: Float, val cols: Int, val rows: Int)

object SpriteData {
${meta.map(m => `    val ${camel(m.name)} = SpriteInfo(${m.w}, ${m.h}, ${m.ax}f, ${m.ay}f, ${m.ppu}f, ${m.cols}, ${m.rows})`).join('\n')}
}
`;
fs.writeFileSync(ktFile, kt);
console.log('done');
